// A shuffled bag gives every quote a turn and prevents a repeat at bag boundaries.
// The picker stays in memory and needs no network request or visitor storage.
export function createQuotePicker(random=Math.random) {
  let bag=[],lastId=null;
  return () => {
    if(!bag.length) {
      bag=MARKET_QUOTES.slice();
      for(let i=bag.length-1;i>0;i--) {
        const j=Math.floor(random()*(i+1));
        [bag[i],bag[j]]=[bag[j],bag[i]];
      }
      if(bag.at(-1).id===lastId) [bag[0],bag[bag.length-1]]=[bag[bag.length-1],bag[0]];
    }
    const quote=bag.pop();lastId=quote.id;return quote;
  };
}
export const nextMarketQuote=createQuotePicker();
